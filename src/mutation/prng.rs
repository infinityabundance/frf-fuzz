//! Counter-based deterministic randomness: Philox4x32-10 (Random123).
//!
//! This is the *only* randomness in the mutation engine. A mutation is
//! reproducible from its [`MutationCoordinate`](crate::mutation::coordinate::MutationCoordinate)
//! because the coordinate maps to an exact (counter, key) pair and the stream
//! is a pure function of that pair — no PRNG heap snapshot, no global state,
//! no wall clock. The same coordinate produces identical streams on scalar
//! CPU, AVX2, CUDA, and ROCm paths (docs/INVARIANTS.md, I2).
//!
//! # Algorithm
//!
//! Philox4x32-10 per Random123: 10 rounds of 2x32 multiply-high/low with the
//! canonical constants
//!
//! ```text
//! M0 = 0xD2511F53   M1 = 0xCD9E8D57
//! W0 = 0x9E3779B9   W1 = 0xBB67AE85
//! ```
//!
//! Each round computes, for counter words `c` and key words `k`:
//!
//! ```text
//! lo0, hi0 = M0 * c0        lo1, hi1 = M1 * c2
//! c' = [ hi1 ^ c1 ^ k0, lo1, hi0 ^ c3 ^ k1, lo0 ]
//! ```
//!
//! then the key is bumped by addition (`k += (W0, W1)`) between rounds.
//!
//! # Test vectors
//!
//! The three official Random123 KAT vectors
//! (`random123/tests/kat_vectors`, `philox4x32 10`) are locked verbatim, plus
//! a six-case table and a 32-block stream generated by an independent pure
//! Python reference (`.phase0/philox_reference.py`) that reproduces the
//! official vectors before emitting anything. See `.phase0/philox_vectors.json`.

use crate::error::{Error, Result};

/// Philox multiplier 0.
pub const PHILOX_M0: u32 = 0xD2511F53;
/// Philox multiplier 1.
pub const PHILOX_M1: u32 = 0xCD9E8D57;
/// Philox Weyl constant 0.
pub const PHILOX_W0: u32 = 0x9E3779B9;
/// Philox Weyl constant 1.
pub const PHILOX_W1: u32 = 0xBB67AE85;
/// Philox4x32-10 round count.
pub const PHILOX_ROUNDS: usize = 10;

/// The Philox4x32-10 bijection.
///
/// Pure function of `(ctr, key)`; no allocation, no global state, no floats.
/// This is the function that must be identical across all acceleration
/// backends (docs/INVARIANTS.md, I3: scalar semantics are normative).
#[inline]
pub fn philox4x32_10(ctr: [u32; 4], key: [u32; 2]) -> [u32; 4] {
    let mut c = ctr;
    let mut k = key;
    for round in 0..PHILOX_ROUNDS {
        let lo0 = c[0].wrapping_mul(PHILOX_M0);
        let hi0 = mulhi(c[0], PHILOX_M0);
        let lo1 = c[2].wrapping_mul(PHILOX_M1);
        let hi1 = mulhi(c[2], PHILOX_M1);
        c = [hi1 ^ c[1] ^ k[0], lo1, hi0 ^ c[3] ^ k[1], lo0];
        if round + 1 < PHILOX_ROUNDS {
            k = [k[0].wrapping_add(PHILOX_W0), k[1].wrapping_add(PHILOX_W1)];
        }
    }
    c
}

/// High 32 bits of the 64-bit product `a * b`.
#[inline]
fn mulhi(a: u32, b: u32) -> u32 {
    ((u64::from(a) * u64::from(b)) >> 32) as u32
}

/// A counter-mode stream over Philox4x32-10.
///
/// Wraps a (counter, key) pair and yields the 4-word blocks in sequence by
/// incrementing `ctr[0]` with carry into `ctr[1]`. The u32 sequence is the
/// canonical byte source: `next_u64` concatenates two u32s little-endian,
/// `fill_bytes` is defined as a sequence of little-endian u32 writes, and
/// `gen_range` is pure rejection sampling on the u32 stream. Everything is
/// integer-only and deterministic.
#[derive(Debug, Clone)]
pub struct CounterRng {
    ctr: [u32; 4],
    key: [u32; 2],
    buf: [u32; 4],
    /// Next unconsumed index into `buf` (0..=4; 4 means refill needed).
    idx: u8,
}

impl CounterRng {
    /// Create a stream from an explicit Philox (counter, key) pair.
    pub fn from_philox(ctr: [u32; 4], key: [u32; 2]) -> Self {
        let mut rng = CounterRng {
            ctr,
            key,
            buf: [0; 4],
            idx: 4,
        };
        rng.refill();
        rng
    }

    /// Derive the stream for one mutation coordinate.
    ///
    /// counter = [generation, mutator<<16 | lane, index_lo, index_hi]
    /// key     = [seed_lo, seed_hi]
    ///
    /// The full 128-bit counter space is spanned by (generation, mutator,
    /// lane, mutation_index) so every mutation in a campaign has a distinct
    /// stream. `probe_params` are carried by the coordinate but intentionally
    /// do not enter the stream: they parameterize *which* experiment runs,
    /// not the random draw itself (documented in docs/ARCHITECTURE.md).
    #[inline]
    pub fn from_coordinate_fields(
        campaign_seed: u64,
        generation: u32,
        mutator_id: u16,
        lane_id: u16,
        mutation_index: u64,
    ) -> Self {
        let ctr = [
            generation,
            (u32::from(mutator_id) << 16) | u32::from(lane_id),
            mutation_index as u32,
            (mutation_index >> 32) as u32,
        ];
        let key = [campaign_seed as u32, (campaign_seed >> 32) as u32];
        Self::from_philox(ctr, key)
    }

    fn refill(&mut self) {
        self.buf = philox4x32_10(self.ctr, self.key);
        self.idx = 0;
        // Increment the counter with carry into ctr[1] only. ctr[2]/ctr[3]
        // (mutation index) are intentionally NOT incremented: the stream for
        // one coordinate is a fixed window derived from its exact counter,
        // and the mutation index space is addressed by the counter itself.
        let (c0, carry) = self.ctr[0].overflowing_add(1);
        self.ctr[0] = c0;
        if carry {
            self.ctr[1] = self.ctr[1].wrapping_add(1);
        }
    }

    /// Next u32 from the stream.
    #[inline]
    pub fn next_u32(&mut self) -> u32 {
        if self.idx >= 4 {
            self.refill();
        }
        let v = self.buf[self.idx as usize];
        self.idx += 1;
        v
    }

    /// Next u64: two little-endian u32s.
    #[inline]
    pub fn next_u64(&mut self) -> u64 {
        let lo = u64::from(self.next_u32());
        let hi = u64::from(self.next_u32());
        lo | (hi << 32)
    }

    /// Fill `out` with deterministic bytes (little-endian u32 writes).
    pub fn fill_bytes(&mut self, out: &mut [u8]) {
        let mut chunks = out.chunks_exact_mut(4);
        for chunk in &mut chunks {
            chunk.copy_from_slice(&self.next_u32().to_le_bytes());
        }
        let rem = chunks.into_remainder();
        if !rem.is_empty() {
            let v = self.next_u32().to_le_bytes();
            rem.copy_from_slice(&v[..rem.len()]);
        }
    }

    /// Uniform integer in `[lo, hi)` by rejection sampling on the u32 stream.
    ///
    /// Deterministic: the number and order of stream draws depends only on the
    /// stream values, which are fixed per coordinate. `hi` must be > `lo`.
    /// The range width is bounded to u32 for simplicity; wider ranges use
    /// [`Self::next_u64`] directly.
    pub fn gen_range_u32(&mut self, lo: u32, hi: u32) -> u32 {
        assert!(hi > lo, "gen_range requires hi > lo");
        let width = hi - lo;
        // Rejection zone: the largest multiple of `width` that fits in u32.
        let zone = u32::MAX - u32::MAX % width;
        loop {
            let v = self.next_u32();
            if v < zone {
                return lo + (v % width);
            }
        }
    }

    /// Uniform usize index in `[0, len)`.
    pub fn gen_index(&mut self, len: usize) -> usize {
        assert!(len > 0, "gen_index requires len > 0");
        self.gen_range_u32(0, len as u32) as usize
    }

    /// Draw a byte in `[0, 256)`.
    #[inline]
    pub fn gen_byte(&mut self) -> u8 {
        self.next_u32() as u8
    }
}

/// Encode a counter to its canonical 16-byte little-endian form.
pub fn encode_counter(ctr: [u32; 4]) -> [u8; 16] {
    let mut out = [0u8; 16];
    for (i, w) in ctr.iter().enumerate() {
        out[i * 4..i * 4 + 4].copy_from_slice(&w.to_le_bytes());
    }
    out
}

/// Decode a canonical 16-byte little-endian counter.
pub fn decode_counter(bytes: &[u8]) -> Result<[u32; 4]> {
    if bytes.len() != 16 {
        return Err(Error::Encoding("counter must be 16 bytes"));
    }
    let mut ctr = [0u32; 4];
    for (i, w) in ctr.iter_mut().enumerate() {
        *w = u32::from_le_bytes(bytes[i * 4..i * 4 + 4].try_into().unwrap());
    }
    Ok(ctr)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Official Random123 KAT: ctr=0, key=0.
    const KAT_1: ([u32; 4], [u32; 2], [u32; 4]) = (
        [0x0000_0000; 4],
        [0x0000_0000, 0x0000_0000],
        [0x6627_E8D5, 0xE169_C58D, 0xBC57_AC4C, 0x9B00_DBD8],
    );
    /// Official Random123 KAT: ctr=max, key=max.
    const KAT_2: ([u32; 4], [u32; 2], [u32; 4]) = (
        [0xFFFF_FFFF; 4],
        [0xFFFF_FFFF, 0xFFFF_FFFF],
        [0x408F_276D, 0x41C8_3B0E, 0xA20B_C7C6, 0x6D54_51FD],
    );
    /// Official Random123 KAT: ctr=pi-ish, key=pi-ish.
    const KAT_3: ([u32; 4], [u32; 2], [u32; 4]) = (
        [0x243F_6A88, 0x85A3_08D3, 0x1319_8A2E, 0x0370_7344],
        [0xA409_3822, 0x299F_31D0],
        [0xD16C_FE09, 0x94FD_CCEB, 0x5001_E420, 0x2412_6EA1],
    );

    /// Verified against the independent Python reference
    /// (`.phase0/philox_reference.py`, which itself passes all KATs).
    const VECTORS: [([u32; 4], [u32; 2], [u32; 4]); 3] = [
        (
            [0, 0, 0, 0],
            [1, 2],
            [0x0598_DE3A, 0x98D2_802E, 0x270F_8F9E, 0xEAB7_09D3],
        ),
        (
            [1, 0, 0, 0],
            [0, 0],
            [0xF8E4_CCA4, 0x5CB2_00DB, 0xB1A5_74EB, 0x097E_FF67],
        ),
        (
            [0xDEAD_BEEF, 0x1234_5678, 0, 0],
            [0xDEAD, 0xBEEF],
            [0x8BAD_FFEE, 0xCB51_1D9E, 0x83C4_42F7, 0x11EC_5803],
        ),
    ];

    /// First 4 blocks of the key=(0,0) stream from counter 0 (from the
    /// verified Python reference).
    const STREAM_KEY0: [[u32; 4]; 4] = [
        [0x6627_E8D5, 0xE169_C58D, 0xBC57_AC4C, 0x9B00_DBD8],
        [0xF8E4_CCA4, 0x5CB2_00DB, 0xB1A5_74EB, 0x097E_FF67],
        [0x04FA_A329, 0x51C7_32A6, 0x2415_13AD, 0x4591_35E4],
        [0xC990_EF29, 0x6A44_74A6, 0x9AC9_134F, 0x6D41_3E04],
    ];

    #[test]
    fn official_kat_vectors() {
        for (ctr, key, want) in [KAT_1, KAT_2, KAT_3] {
            assert_eq!(philox4x32_10(ctr, key), want);
        }
    }

    #[test]
    fn verified_additional_vectors() {
        for (ctr, key, want) in VECTORS {
            assert_eq!(philox4x32_10(ctr, key), want);
        }
    }

    #[test]
    fn stream_matches_reference() {
        let mut rng = CounterRng::from_philox([0, 0, 0, 0], [0, 0]);
        for block in STREAM_KEY0 {
            for want in block {
                assert_eq!(rng.next_u32(), want);
            }
        }
    }

    #[test]
    fn fill_bytes_is_little_endian_u32_writes() {
        let mut rng = CounterRng::from_philox([0, 0, 0, 0], [0, 0]);
        let mut out = [0u8; 10]; // 2 full u32s + 2-byte tail
        rng.fill_bytes(&mut out);
        let mut rng2 = CounterRng::from_philox([0, 0, 0, 0], [0, 0]);
        let mut expect = [0u8; 10];
        let w0 = rng2.next_u32().to_le_bytes();
        let w1 = rng2.next_u32().to_le_bytes();
        let w2 = rng2.next_u32().to_le_bytes();
        expect[0..4].copy_from_slice(&w0);
        expect[4..8].copy_from_slice(&w1);
        expect[8..10].copy_from_slice(&w2[..2]);
        assert_eq!(out, expect);
    }

    #[test]
    fn coordinate_derivation_is_bijective_in_fields() {
        // Distinct (generation, mutator, lane, index) => distinct stream
        // starts (checked via first word).
        let a = CounterRng::from_coordinate_fields(1, 2, 3, 4, 5).next_u32();
        let b = CounterRng::from_coordinate_fields(1, 2, 3, 4, 6).next_u32();
        let c = CounterRng::from_coordinate_fields(1, 2, 4, 4, 5).next_u32();
        let d = CounterRng::from_coordinate_fields(2, 2, 3, 4, 5).next_u32();
        assert_ne!(a, b);
        assert_ne!(a, c);
        assert_ne!(a, d);
    }

    #[test]
    fn gen_range_is_in_bounds_and_deterministic() {
        let mut rng = CounterRng::from_philox([7, 0, 0, 0], [3, 1]);
        let mut seen = std::collections::BTreeSet::new();
        for _ in 0..1000 {
            let v = rng.gen_range_u32(10, 20);
            assert!((10..20).contains(&v));
            seen.insert(v);
        }
        assert_eq!(seen.len(), 10); // rejection sampling covers the full range
                                    // Determinism: two independent replays produce identical sequences.
        let mut rng_a = CounterRng::from_philox([7, 0, 0, 0], [3, 1]);
        let mut rng_b = CounterRng::from_philox([7, 0, 0, 0], [3, 1]);
        for _ in 0..1000 {
            assert_eq!(rng_a.gen_range_u32(10, 20), rng_b.gen_range_u32(10, 20));
        }
    }

    #[test]
    fn counter_encode_decode_roundtrip() {
        let ctr = [0xDEAD_BEEF, 0x1234_5678, 0, 1];
        let bytes = encode_counter(ctr);
        assert_eq!(bytes.len(), 16);
        assert_eq!(decode_counter(&bytes).unwrap(), ctr);
        assert!(decode_counter(&bytes[..15]).is_err());
    }
}
